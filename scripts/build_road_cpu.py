"""Generate constant-colour, four-group-unrolled planar road handlers."""
from build_paths import GENERATED
lines=['''; Generated by build_road_cpu.py. A0=row, D0=ink, fixed 320px/160 bytes.
; Land = original plane0 & ~plane1. Each handler has no per-plane branches.
        section text
        xdef RR_RoadCPU
RR_RoadCPU:
        move.l d2,-(sp)
        andi.w #15,d0
        add.w d0,d0
        lea .table(pc),a1
        move.w (a1,d0.w),d0
        lea (a1,d0.w),a1
        moveq #4,d1
        jmp (a1)
.table:''']
lines += ['        dc.w .ink%d-.table'%ink for ink in range(16)]
for ink in range(16):
    lines.append('.ink%d:'%ink)
    for group in range(4):
        lines += ['        move.w (a0)+,d0','        move.w (a0)+,d2',
                  '        not.w d2','        and.w d2,d0',
                  '        move.w d0,d2','        not.w d2']
        # Land is already set in plane0 and absent from plane1.
        if not ink&1: lines.append('        and.w d2,-4(a0)')
        if ink&2: lines.append('        or.w d0,-2(a0)')
        for plane in (2,3):
            lines.append('        or.w d0,(a0)+' if ink&(1<<plane) else '        and.w d2,(a0)+')
    lines += ['        dbra d1,.ink%d'%ink,'        move.l (sp)+,d2','        rts']
(GENERATED/'road_cpu.s').write_text('\n'.join(lines)+'\n')
