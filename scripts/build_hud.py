"""Expand the captured ANTIC font once, offline, to 16-pixel ST masks."""
import re
from build_paths import ASSETS, GENERATED
source=(ASSETS/'hud_assets.inc').read_text()
font=bytes(int(v,16) for v in re.findall(r'0x([0-9a-fA-F]+)',source.split('};')[0]))
assert len(font)==512
masks=[sum(0xc000 >> (bit*2) for bit in range(8) if v & (128 >> bit)) for v in font]
lines=['/* Generated by build_hud.py, captured A8 font, doubled horizontally. */',
       '#include <godlib/base/base.h>', 'const U16 rrHudMasks[512] = {']
for i in range(0,512,8): lines.append('    '+','.join('0x%04x'%v for v in masks[i:i+8])+',')
lines.append('};')
assert masks[:8]==[0]*8
# Only hot digits and the reserve icon need native planar pairs. Other glyphs
# retain the compact masks, avoiding a full three-colour font atlas.
glyphs=list(range(16,26))+[28]
offsets=[glyphs.index(i)*64 if i in glyphs else 0x8000+i*16 for i in range(64)]
lines += ['const U16 rrHudNativeOffsets[64] = {']
for i in range(0,64,8): lines.append('    '+','.join('0x%04x'%v for v in offsets[i:i+8])+',')
lines += ['};','const U32 rrHudNativePlanes[11][16] = {']
for glyph in glyphs:
    words=[]
    for mask in masks[glyph*8:glyph*8+8]: words.extend(((mask^65535)<<16,0xffff0000|mask))
    lines.append('    {'+','.join('0x%08xUL'%v for v in words)+'},')
lines += ['};','const U16 rrHudCellOffsets[60] = {']
for row,top in enumerate((6,18,26)):
    lines.append('    '+','.join(str(top*160+column*8) for column in range(20))+',')
lines.append('};')
(GENERATED/'hud_masks.c').write_text('\n'.join(lines)+'\n')
