"""Convert the recovered A8 effect scripts to compact PAL YM register frames.

YM noise is not POKEY poly17: this is a native PSG approximation, not PCM.
See README.md for the native YM channel mapping.
"""
import math
from build_paths import ASSETS, GENERATED

def volume(amplitude):
    if not amplitude:
        return 0
    return max(1, min(15, round(15 + 2 * math.log2(amplitude / 60))))

def frame(divider, amplitude, noise=False):
    period = max(1, min(4095, round(2000000 * 56 * (divider + 1) / (16 * 1789790))))
    np = max(1, min(31, round(period / 2)))
    return period, np, volume(amplitude), 2 if noise else 1, 0

def main():
    rom = (ASSETS / 'RIVER_A8.BIN').read_bytes()
    effects = []
    for n in range(4, 16):
        # Quiet noise-only engine, pitched across the full throttle range.
        # Use native YM noise range instead of clamping every speed to 31.
        effects.append([(0, 31-n, 6 if n < 8 else 7, 2, 0)])
    for divider in (63, 31):
        effects.append([frame(divider, v*3) for v in range(8, 0, -1)])
    effects.append([frame((28-t)*6 & 255, 28) for t in range(15, 0, -1)])
    # Deterministic offline RANDOM substitute; no per-frame random/division.
    state = 0xace1
    randoms = []
    for _ in range(56):
        state = (state >> 1) ^ (0xb400 if state & 1 else 0)
        randoms.append(state & 255)
    effects.append([frame(r | 24, ((v >> 1)+4)*2, True)
                    for r,v in zip(randoms,range(23,0,-1))])
    effects.append([frame(0x39,(v >> 1)*4,True) for v in range(31,0,-1)])
    effects.append([frame(17,(v//2 & 15)*3,True) for v in range(34,0,-1)])
    notes = rom[0x14e1:0x14e5]
    effects.append([frame(notes[(v-1) >> 4],round(((v-1)&15)*1.8))
                    for v in range(64,0,-1)])
    effects.append([frame(v*2,24 if v >= 28 else 0) for v in range(62,0,-1)])
    effects.append([frame(d,30) for d in rom[0x14c1:0x14d1]] +
                   [frame(r | 32,30,True) for r in randoms[:40]])
    assert len(effects) == 21
    lines = ['/* Generated by build_psg.py; native YM2149, 50 Hz. */',
             '#include "audio_psg.h"']
    for i,frames in enumerate(effects):
        lines.append('static const RRPsgFrame effect%d[] = {' % i)
        lines.extend('    {%d,%d,%d,%d,%d},' % f for f in frames)
        lines.append('};')
    lines.append('const RRPsgEffect rrPsgEffects[21] = {')
    lines.extend('    {effect%d,%d},' % (i,len(f)) for i,f in enumerate(effects))
    lines.append('};')
    (GENERATED / 'audio_psg_data.c').write_text('\n'.join(lines)+'\n')
    print('PSG: %d frames, %d bytes including descriptors' %
          (sum(map(len,effects)),sum(map(len,effects))*6 + 21*6))

if __name__ == '__main__':
    main()
