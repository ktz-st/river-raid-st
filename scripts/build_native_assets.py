"""Extract audited C tables and preconvert PMG to masked four-plane ST sprites."""
import hashlib
import json
import struct
from rom_data_layout import RANGES
from build_paths import ASSETS, BUILD, GENERATED
from st_palette import ST_PALETTE, A8_TO_ST
from png_assets import load_sprites,load_scenery

rom = (ASSETS/'RIVER_A8.BIN').read_bytes()
assert len(rom) == 8192
inks = A8_TO_ST
st_palette = ST_PALETTE
used = {}
def read(address, size, category):
    assert 0xa000 <= address <= address+size <= 0xc000
    used.setdefault(category,set()).update(range(address,address+size))
    return rom[address-0xa000:address-0xa000+size]
def byte(address, category): return read(address,1,category)[0]
def pointer(address, category): return int.from_bytes(read(address,2,category),'little')
def array(values, width=2):
    return '\n'.join('    '+', '.join(f'0x{x:0{width}x}' for x in values[i:i+12])+','
                     for i in range(0,len(values),12))

h = ['/* Generated by build_native_assets.py; original ROM is a build input only. */',
     '#ifndef RR_NATIVE_ASSETS_H', '#define RR_NATIVE_ASSETS_H',
     '#include <stdint.h>', '#include <godlib/sprite/sprite.h>',
     'typedef struct {']
for name,start,size in RANGES: h.append(f'    uint8_t {name}[{size}]; /* ${start:04x} */')
h += ['} RRGeneratorTables;', 'extern const RRGeneratorTables rrGeneratorTables;',
      'extern const uint8_t rrSceneDefaults[42], rrGameDefaults[6], rrRoadInks[20];',
      'extern const uint16_t rrPalette[16], gPlayerMasks[7][14];',
      'extern const sSprite rrEnemySprites[129], rrPlayerSprites[7];',
      'extern const uint16_t *const rrEnemyMono[129], *const rrPlayerMono[7];', '#endif']
c = ['/* Generated native assets: no 6502 code, A8 RAM image or display list. */',
     '#include "native_assets.h"', '#include <stddef.h>',
     'const RRGeneratorTables rrGeneratorTables = {']
offset=0
inventory=[]
scenery_rows=load_scenery()
for name,start,size in RANGES:
    values=scenery_rows if name=='decoration_rows' else read(start,size,'generator')
    c += [f'    .{name} = {{', array(values), '    },']
    inventory.append(dict(name=name,address=f'{start:04x}',bytes=size,packed_offset=offset))
    offset+=size
c += ['};']
for item in inventory:
    c.append(f'_Static_assert(offsetof(RRGeneratorTables, {item["name"]}) == {item["packed_offset"]}, "table ASM offset");')
c.append(f'_Static_assert(sizeof(RRGeneratorTables) == {offset}, "table ASM size");')
for name,values,ctype,width in (
    ('rrSceneDefaults',read(0xbae1,42,'initialization'),'uint8_t',2),
    ('rrGameDefaults',[byte(0xb494+i*4,'initialization') for i in range(4)]+
                       [byte(0xb4a4,'initialization'),byte(0xb4a8,'initialization')],'uint8_t',2),
    ('rrRoadInks',[inks[byte(0xb4f8-y,'road')] for y in range(20)],'uint8_t',2),
    ('rrPalette',st_palette,'uint16_t',4)):
    c += [f'const {ctype} {name}[{len(values)}] = {{',array(values,width),'};']

assets,player=load_sprites()

# Share identical native graphics/masks between animation poses and directions.
blocks={}; total_words=0
def block(words):
    global total_words
    if words not in blocks:
        name=f'rrSpriteWords{len(blocks)}'; blocks[words]=name; total_words+=len(words)
        c.extend([f'static const uint16_t {name}[{len(words)}] = {{',array(words,4),'};'])
    return blocks[words]
descriptors=[]
for label,items in (('rrEnemySprites',assets),('rrPlayerSprites',player)):
    entries=[]
    for pose,(width,height,mask,gfx) in sorted(items.items()):
        m=f'gPlayerMasks[{pose}]' if label=='rrPlayerSprites' else block(mask)
        g=block(gfx)
        entries.append(f'    [{pose}] = {{(U16*){g}, (U16*){m}, {width}, {height}, 4, 4}},')
    descriptors += [f'const sSprite {label}[{129 if label=="rrEnemySprites" else 7}] = {{',*entries,'};']
c += descriptors
c += ['const uint16_t gPlayerMasks[7][14] = {']
for pose in range(7): c += ['    {',array(player[pose][2],4),'    },']
c += ['};']
# Compact scanlines: colour dispatch offset + opaque bits/shared mask index.
# Share preshifted opaque masks across 32px poses, not entire sprites.
patterns=sorted({((mask[y*2]^65535)<<16)|(mask[y*2+1]^65535) for items in (assets,player) for width,height,mask,gfx in items.values() if width==32 for y in range(height)})
pattern_index={bits:i*8 for i,bits in enumerate(patterns)}
assert len(patterns)*8<32768
shift_banks=[]
for shift in range(16):
    words=[]
    for bits in patterns:
        shifted=(bits<<16)>>shift
        words.extend((shifted>>32,(shifted>>16)&65535,shifted&65535,0))
    shift_banks.append(block(tuple(words)))
c += ['const uint16_t *const rrMonoShifts32[16] = {', *('    '+b+',' for b in shift_banks), '};']
mono_words=0
for label,items,count in (('rrEnemyMono',assets,129),('rrPlayerMono',player,7)):
    entries=[]
    for pose,(width,height,mask,gfx) in sorted(items.items()):
        if width not in (16,32): continue
        groups=width//16
        rows=[]
        for y in range(height):
            bits=[mask[y*groups+group]^65535 for group in range(groups)]; ink=0
            for group in range(groups):
                for plane in range(4):
                    value=gfx[(y*groups+group)*4+plane]
                    assert value in (0,bits[group]),('not monochrome scanline',label,pose,y)
                    if value: ink|=1<<plane
            for group in range(groups):
                for plane in range(4):
                    assert gfx[(y*groups+group)*4+plane]==(bits[group] if ink&(1<<plane) else 0)
            rows.extend((ink*64,*bits) if width==16 else (ink*64,pattern_index[(bits[0]<<16)|bits[1]],0))
        mono_words+=len(rows)
        entries.append(f'    [{pose}] = {block(tuple(rows))},')
    c += [f'const uint16_t *const {label}[{count}] = {{',*entries,'};']
(GENERATED/'native_assets.h').write_text('\n'.join(h)+'\n')
(GENERATED/'native_assets.c').write_text('\n'.join(c)+'\n')

def ranges(addresses):
    result=[]
    for a in sorted(addresses):
        if result and result[-1][1]==a: result[-1][1]+=1
        else: result.append([a,a+1])
    return [[f'{a:04x}',f'{b:04x}'] for a,b in result]
report=dict(rom_sha256=hashlib.sha256(rom).hexdigest(),generator_tables=inventory,
            generator_table_bytes=offset,native_sprite_words=total_words+7*14,
            sprite_poses=len(assets),player_poses=len(player),
            mono_row_words_before_dedup=mono_words,
            shared_preshift_patterns=len(patterns),shared_preshift_bytes=len(patterns)*128,
            categories={k:dict(bytes=len(v),ranges_end_exclusive=ranges(v)) for k,v in used.items()},
            total_source_bytes=len(set().union(*used.values())),
            note='Audited full table ranges, not just trace coverage; terrain remains compact row commands.')
(BUILD/'rom_inventory.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'Native assets: {offset} generator bytes, {(total_words+7*14)*2} sprite/mask/CPU-stream bytes, {report["total_source_bytes"]} ROM source bytes retained/converted')
